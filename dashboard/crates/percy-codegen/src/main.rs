//! Generates `crates/percy-client/src/generated.rs` from `crates/percy-client/openapi.json`.
//!
//! Which schemas are emitted is automatic: every component schema reachable from a 2xx JSON
//! response body, transitively. Request-body models are not generated (yet) — the client still
//! builds those as `serde_json::Value`. `cargo run -p percy-codegen -- --check` fails when the
//! committed `generated.rs` is stale. See `crates/percy-client/GENERATION.md`.

use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use serde_json::Value;
use typify::{TypeSpace, TypeSpacePatch, TypeSpaceSettings};

const HEADER: &str = "// @generated by `cargo run -p percy-codegen` from openapi.json. DO NOT EDIT.\n\
// Regenerate after any API change: `poetry run python scripts/export_openapi.py && cargo run -p percy-codegen`.\n\
// See GENERATION.md.\n\n";

/// `#/components/schemas/Foo` -> `Foo`.
fn ref_name(r: &str) -> &str {
    r.rsplit('/').next().unwrap_or(r)
}

/// Collects every `$ref`'d schema name below `v`.
fn refs_in(v: &Value, out: &mut Vec<String>) {
    match v {
        Value::Object(m) => {
            for (k, val) in m {
                match (k.as_str(), val) {
                    ("$ref", Value::String(s)) => out.push(ref_name(s).to_string()),
                    _ => refs_in(val, out),
                }
            }
        }
        Value::Array(a) => a.iter().for_each(|x| refs_in(x, out)),
        _ => {}
    }
}

/// Names of the schemas reachable from 2xx JSON responses.
fn response_schemas(spec: &Value) -> BTreeSet<String> {
    let mut todo = Vec::new();
    for (_, ops) in spec["paths"].as_object().expect("paths") {
        for (_, op) in ops.as_object().expect("operations") {
            for (code, resp) in op["responses"].as_object().into_iter().flatten() {
                if code.starts_with('2') {
                    if let Some(schema) = resp.pointer("/content/application~1json/schema") {
                        refs_in(schema, &mut todo);
                    }
                }
            }
        }
    }
    let all = &spec["components"]["schemas"];
    let mut seen = BTreeSet::new();
    while let Some(name) = todo.pop() {
        if seen.insert(name.clone()) {
            refs_in(&all[&name], &mut todo);
        }
    }
    seen
}

/// Can `schema` be a Rust type that implements `Default`? Structs whose every field is a primitive,
/// collection, `Option` or another such struct can; enums (`enum`/`oneOf`/non-null `anyOf`) cannot.
/// The dashboard degrades a failed Percy call with `unwrap_or_default()`, so structs that can derive it do.
fn defaultable(all: &Value, schema: &Value, depth: u8) -> bool {
    if depth > 8 {
        return false;
    }
    if let Some(r) = schema["$ref"].as_str() {
        return defaultable(all, &all[ref_name(r)], depth + 1);
    }
    if schema.get("enum").is_some() || schema.get("oneOf").is_some() || schema.get("allOf").is_some() {
        return false;
    }
    if let Some(any) = schema["anyOf"].as_array() {
        // `X | None` is an Option (always Default); any other union is an enum.
        return any.iter().filter(|s| s["type"] != "null").count() <= 1;
    }
    match schema["properties"].as_object() {
        Some(props) if schema["type"] == "object" => props.values().all(|p| defaultable(all, p, depth + 1)),
        _ => true,
    }
}

fn render(spec: &Value) -> String {
    let names = response_schemas(spec);
    let mut types: BTreeMap<String, schemars::schema::Schema> = BTreeMap::new();
    for name in &names {
        let schema = serde_json::from_value(spec["components"]["schemas"][name].clone())
            .unwrap_or_else(|e| panic!("schema {name}: {e}"));
        types.insert(name.clone(), schema);
    }
    let all = &spec["components"]["schemas"];
    let mut settings = TypeSpaceSettings::default();
    for name in &names {
        let s = &all[name];
        if s["type"] == "object" && defaultable(all, s, 0) {
            settings.with_patch(name, TypeSpacePatch::default().with_derive("Default"));
        }
    }
    let mut ts = TypeSpace::new(&settings);
    ts.add_ref_types(types).expect("typify");
    let file = syn::parse2(ts.to_stream()).expect("generated code parses");
    format!("{HEADER}{}", prettyplease::unparse(&file))
}

fn main() {
    let client = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../percy-client");
    let spec: Value =
        serde_json::from_str(&std::fs::read_to_string(client.join("openapi.json")).expect("openapi.json"))
            .expect("openapi.json is JSON");
    let out = client.join("src/generated.rs");
    let text = render(&spec);
    if std::env::args().any(|a| a == "--check") {
        let have = std::fs::read_to_string(&out).unwrap_or_default().replace("\r\n", "\n");
        if have != text {
            eprintln!("generated.rs is stale: run `cargo run -p percy-codegen`");
            std::process::exit(1);
        }
    } else {
        std::fs::write(&out, text).expect("write generated.rs");
        println!("wrote {}", out.display());
    }
}
